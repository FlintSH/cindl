import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  type ConfigPlugin,
} from 'expo/config-plugins'

/**
 * Network policy for the generated Android project.
 *
 * - Cleartext HTTP is refused for every host except the device's own
 *   loopback IP literals (127.0.0.1, ::1): a Hermes origin must be https
 *   unless it runs on the device itself or is forwarded to it for testing.
 * - Only system certificate authorities are trusted; user-installed CAs are
 *   not (the Android default for apps targeting API 24+, written out here so
 *   it cannot drift).
 * - Debug builds (never shipped) may also reach a local Metro dev server; the
 *   debug source set overrides the resource with that one extra allowance.
 *
 * The sign-in callback does not need cleartext from the app: the system
 * browser makes that request to Cindl's own loopback listener.
 */
function networkSecurityConfig(extraCleartextHosts: readonly string[]): string {
  const hosts = ['127.0.0.1', '::1', ...extraCleartextHosts]
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/android/plugins/withNetworkSecurity.ts. Do not edit. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
  <domain-config cleartextTrafficPermitted="true">
${hosts.map((host) => `    <domain includeSubdomains="false">${host}</domain>`).join('\n')}
  </domain-config>
</network-security-config>
`
}

export const RELEASE_NETWORK_SECURITY_CONFIG = networkSecurityConfig([])
/** Metro dev server over adb reverse (localhost) or the emulator host alias. */
export const DEBUG_NETWORK_SECURITY_CONFIG = networkSecurityConfig([
  'localhost',
  '10.0.2.2',
])

const RESOURCE = '@xml/network_security_config'

export const withNetworkSecurity: ConfigPlugin = (config) => {
  const withFiles = withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const root = modConfig.modRequest.platformProjectRoot
      for (const [sourceSet, content] of [
        ['main', RELEASE_NETWORK_SECURITY_CONFIG],
        ['debug', DEBUG_NETWORK_SECURITY_CONFIG],
      ] as const) {
        const dir = path.join(root, 'app/src', sourceSet, 'res/xml')
        await mkdir(dir, { recursive: true })
        await writeFile(path.join(dir, 'network_security_config.xml'), content)
      }
      return modConfig
    },
  ])
  return withAndroidManifest(withFiles, (modConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(
      modConfig.modResults,
    )
    application.$['android:networkSecurityConfig'] = RESOURCE
    application.$['android:usesCleartextTraffic'] = 'false'
    return modConfig
  })
}

export default withNetworkSecurity
