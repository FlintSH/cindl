import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
  type ConfigPlugin,
} from 'expo/config-plugins'

const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external'] as const
const excludeAll = DOMAINS.map(
  (domain) => `    <exclude domain="${domain}" path="." />`,
).join('\n')

/**
 * Nothing Cindl keeps on the device goes to a cloud backup or a device-to-
 * device transfer. `allowBackup=false` alone is not honoured for transfers on
 * every Android 12+ device, so explicit rules exclude every domain as well.
 */
export const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/android/plugins/withNoBackups.ts. Do not edit. -->
<data-extraction-rules>
  <cloud-backup>
${excludeAll}
  </cloud-backup>
  <device-transfer>
${excludeAll}
  </device-transfer>
</data-extraction-rules>
`

export const withNoBackups: ConfigPlugin = (config) => {
  const withFile = withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const dir = path.join(
        modConfig.modRequest.platformProjectRoot,
        'app/src/main/res/xml',
      )
      await mkdir(dir, { recursive: true })
      await writeFile(path.join(dir, 'data_extraction_rules.xml'), DATA_EXTRACTION_RULES)
      return modConfig
    },
  ])
  return withAndroidManifest(withFile, (modConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(
      modConfig.modResults,
    )
    application.$['android:allowBackup'] = 'false'
    application.$['android:fullBackupContent'] = 'false'
    application.$['android:dataExtractionRules'] = '@xml/data_extraction_rules'
    return modConfig
  })
}
